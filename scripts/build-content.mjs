// Turns the dashboard's content/ folder into data the site imports:
//   src/data/generated/content.json  every entry, images replaced by { "__img": key }
//   src/data/generated/images.ts     a static import per image (keeps blur placeholders)
// Runs before `next dev` / `next build`. Pass --watch to rebuild on every change.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CONTENT = path.join(ROOT, "content");
const OUT = path.join(ROOT, "src/data/generated");
const IMAGE = /\.(jpe?g|png|webp|gif|avif)$/i;

const SINGLETONS = { settings: "settings", pageText: "page-text", home: "home", about: "about", work: "work", store: "store" };
const COLLECTIONS = { projects: "projects", articles: "articles" };

function readEntry(dir, keys) {
  const file = path.join(dir, "index.json");
  if (!fs.existsSync(file)) return null;
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const rel = path.relative(CONTENT, dir).split(path.sep).join("/");
  const walk = (v) => {
    if (typeof v === "string" && IMAGE.test(v) && !v.startsWith("/") && fs.existsSync(path.join(dir, v))) {
      const key = `${rel}/${v}`;
      keys.add(key);
      return { __img: key };
    }
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === "object") return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)]));
    return v;
  };
  return walk(data);
}

function build() {
  const keys = new Set();
  const out = {};
  for (const [name, dir] of Object.entries(SINGLETONS)) out[name] = readEntry(path.join(CONTENT, dir), keys) ?? {};
  for (const [name, dir] of Object.entries(COLLECTIONS)) {
    const base = path.join(CONTENT, dir);
    out[name] = !fs.existsSync(base) ? [] : fs.readdirSync(base, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => ({ slug: d.name, ...readEntry(path.join(base, d.name), keys) }))
      .filter((e) => e.title);
  }

  const sorted = [...keys].sort();
  const lines = [
    "// Generated by scripts/build-content.mjs. Do not edit.",
    'import type { StaticImageData } from "next/image";',
    ...sorted.map((k, i) => `import i${i} from "../../../content/${k}";`),
    "",
    "export const images: Record<string, StaticImageData> = {",
    ...sorted.map((k, i) => `  ${JSON.stringify(k)}: i${i},`),
    "};",
    "",
  ];
  fs.mkdirSync(OUT, { recursive: true });
  const write = (f, text) => {
    const p = path.join(OUT, f);
    if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== text) fs.writeFileSync(p, text);
  };
  write("content.json", JSON.stringify(out, null, 2) + "\n");
  write("images.ts", lines.join("\n"));
  return { projects: out.projects.length, articles: out.articles.length, images: sorted.length };
}

const stats = build();
console.log(`content: ${stats.projects} projects, ${stats.articles} articles, ${stats.images} images`);

if (process.argv.includes("--watch")) {
  let timer;
  fs.watch(CONTENT, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { build(); } catch (e) { console.error("content build failed:", e.message); }
    }, 200);
  });
  console.log("watching content/ for changes");
}
